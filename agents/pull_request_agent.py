def section(title: str, items: list[str]) -> str:

    if not items:
        return f"## {title}\n\nNone\n"

    body = "\n".join(f"- {item}" for item in items)

    return f"## {title}\n\n{body}\n"


def description(task: Task) -> str:
    """The pull request body, built from the run itself."""

    sources = [
        item.path
        for item in task.generated_files
        if item.file_type == FileType.SOURCE
    ]

    tests = [
        item.path
        for item in task.generated_files
        if item.file_type == FileType.TEST
    ]

    parts = [
        "## Summary",
        "",
        task.description.strip()
        or "No description was given.",
        "",
        "## Architecture Score",
        "",
        f"{task.architecture_score}",
        "",
        "## Recommendation",
        "",
        task.recommendation.value,
        "",
        "## Review Iterations",
        "",
        f"{task.review_iterations}",
        "",
        section("Generated Files", sources),
        section("Generated Tests", tests),
        section("Structural Findings", task.structural),
        section("Blockers", task.blockers),
        section("Warnings", task.warnings),
        section("Suggestions", task.suggestions),
        "---",
        "",
        (
            "Generated by DevLoop. Approved by a "
            "human before this branch was pushed."
        ),
    ]

    return "\n".join(parts)


def title(task: Task) -> str:

    return f"feat: {summary(task.description)}"


def task_state(record: Task | None) -> str:

    if record is None:
        return "not run yet"

    if record.status == TaskStatus.REJECTED:
        return "rejected"

    if record.git_operation.commit_hash:
        return f"committed {record.git_operation.short_hash}"

    return "awaiting review"


def plan_title(plan: Plan) -> str:
    """From the requirement's title, its first line."""

    first = plan.epic.strip().splitlines()[0] if plan.epic.strip() else ""

    return f"feat: {summary(first)}"


def plan_description(plan: Plan, records: list[Task]) -> str:
    """The body for a plan's pull request: every task in it.

    A plan's branch is pushed once per task, so a body
    built from one task described a fifth of the change.
    This one is rebuilt from the plan and the task records
    on its branch every time the branch is pushed.
    """

    by_id = {record.id: record for record in records}

    rows: list[str] = []

    committed: list[Task] = []

    # Findings and costs are labelled like the checklist,
    # so a reader can find the task they belong to.
    labels: dict[str, str] = {}

    for item in plan.tasks:

        execution = plan.execution(item.id)

        record = (
            by_id.get(execution.task_record_id)
            if execution is not None
            else None
        )

        done = record is not None and bool(
            record.git_operation.commit_hash
        )

        rows.append(
            f"- [{'x' if done else ' '}] **{item.id}. "
            f"{item.title}** — {task_state(record)}"
        )

        if record is not None and record.status != TaskStatus.REJECTED:

            rows.append(
                f"  architecture {record.architecture_score}/100"
                f" · {record.recommendation.value}"
                f" · compile {record.compile_result.status.value}"
                f" · tests {record.test_result.status.value}"
            )

        if done:
            committed.append(record)
            labels[record.id] = f"{item.id}. {item.title}"

    files = sorted(
        {
            item.path
            for record in committed
            for item in record.generated_files
        }
    )

    def findings(kind: str) -> list[str]:

        return [
            f"**{labels[record.id]}**: {finding}"
            for record in committed
            for finding in getattr(record, kind)
        ]

    costs = [
        f"**{labels[record.id]}**: {step.detail}"
        for record in committed
        for step in record.steps
        if step.name == "step.usage"
    ]

    parts = [
        "## Requirement",
        "",
        plan.epic.strip() or "No description was given.",
        "",
        "## Tasks",
        "",
        *rows,
        "",
        section("Files", files),
        section("Structural Findings", findings("structural")),
        section("Blockers", findings("blockers")),
        section("Warnings", findings("warnings")),
        section("Cost", costs),
        "---",
        "",
        (
            "Generated by DevLoop. Every task was "
            "approved by a human before it was committed; "
            "this description is rebuilt on every push."
        ),
    ]

    return "\n".join(parts)


class PullRequestAgent:
    """Opens a pull request for a pushed, approved task.

    It can create one and read one back. Merging, closing
    and commenting are not implemented, and the service it
    uses refuses those calls outright.
    """

    @staticmethod
    def service(task: Task) -> GitHubService:

        return GitHubService.from_remote(
            task.git_push.remote_url
        )

    @staticmethod
    def can_create(task: Task) -> tuple[bool, str]:
        """Whether a pull request may be opened, and why not."""

        if task.status != TaskStatus.APPROVED:
            return (
                False,
                "The task has not been approved yet.",
            )

        if not task.git_push.pushed:
            return (
                False,
                "The branch has not been pushed yet.",
            )

        if task.pull_request.exists:
            return (
                False,
                (
                    "A pull request already exists for "
                    "this task."
                ),
            )

        try:
            service = PullRequestAgent.service(task)

        except GitHubError as error:
            return False, str(error)

        if not service.has_token:
            return (
                False,
                (
                    "No GitHub token. Set GITHUB_PAT in "
                    ".env to create pull requests."
                ),
            )

        return True, ""

    @staticmethod
    def text(
        task: Task,
        plan: Plan | None = None,
        records: list[Task] | None = None,
    ) -> tuple[str, str]:
        """Title and body: the plan's, or the task's own."""

        if plan is not None:
            return (
                plan_title(plan),
                plan_description(plan, records or [task]),
            )

        return title(task), description(task)

    @staticmethod
    def preview(
        task: Task,
        plan: Plan | None = None,
        records: list[Task] | None = None,
    ) -> dict:
        """What would be opened, without opening it."""

        owner = ""

        repository = ""

        try:
            service = PullRequestAgent.service(task)

            owner = service.owner

            repository = service.repository

        except GitHubError:
            pass

        heading, body = PullRequestAgent.text(task, plan, records)

        return {
            "owner": owner,
            "repository": repository,
            "branch": task.git_push.branch_name,
            "title": heading,
            "body": body,
        }

    @staticmethod
    def to_info(
        data: dict,
        branch: str,
        base: str,
    ) -> PullRequestInfo:

        state = PullRequestState.parse(
            data.get("state", "")
        )

        if data.get("merged_at"):
            state = PullRequestState.MERGED

        return PullRequestInfo(
            id=int(data.get("number") or 0),
            url=str(data.get("html_url") or ""),
            branch=branch,
            base=base,
            state=state,
            created_at=str(data.get("created_at") or ""),
        )

    @staticmethod
    def execute(
        task: Task,
        base: str = "",
        plan: Plan | None = None,
        records: list[Task] | None = None,
    ) -> PullRequestInfo:
        """Opens the pull request, or records why it failed.

        A failure is returned rather than raised, because
        it must not undo the approval, the commit or the
        push that already succeeded.
        """

        branch = task.git_push.branch_name

        allowed, reason = PullRequestAgent.can_create(task)

        if not allowed:
            return PullRequestInfo(
                branch=branch,
                state=PullRequestState.FAILED,
                error=reason,
            )

        heading, body = PullRequestAgent.text(task, plan, records)

        try:
            service = PullRequestAgent.service(task)

            existing = service.find_pull_request(branch)

            if existing:

                print(
                    "PULL REQUEST AGENT: one already "
                    f"exists for {branch}"
                )

                # Another task of the same plan opened it;
                # what it says is now out of date.
                if plan is not None and existing.get("number"):
                    service.update_pull_request(
                        int(existing["number"]),
                        heading,
                        body,
                    )

                return PullRequestAgent.to_info(
                    existing,
                    branch,
                    str(
                        (existing.get("base") or {}).get(
                            "ref"
                        )
                        or base
                    ),
                )

            target = base or service.default_branch()

            data = service.create_pull_request(
                branch,
                target,
                heading,
                body,
            )

            info = PullRequestAgent.to_info(
                data,
                branch,
                target,
            )

            if not info.created_at:
                info.created_at = datetime.now(
                    UTC
                ).isoformat()

            print("=" * 80)
            print("PULL REQUEST AGENT")
            print("=" * 80)
            print(f"{info.label} {info.state.value}")
            print(info.url)
            print("=" * 80)

            return info

        except (GitHubError, OSError, ValueError) as error:

            print(f"PULL REQUEST AGENT: failed: {error}")

            return PullRequestInfo(
                branch=branch,
                base=base,
                state=PullRequestState.FAILED,
                error=str(error),
            )

    @staticmethod
    def sync(
        task: Task,
        plan: Plan,
        records: list[Task],
    ) -> PullRequestInfo | None:
        """After a push: rewrite the plan's PR, if there is one.

        Returns the request it updated, or None when there
        is none yet -- opening one stays a human's click.
        Failure is reported, never raised: the push it
        follows has already succeeded.
        """

        branch = task.git_push.branch_name or task.branch

        try:
            service = PullRequestAgent.service(task)

            if not service.has_token:
                return None

            existing = service.find_pull_request(branch)

            if not existing or existing.get("state") != "open":
                return None

            heading, body = PullRequestAgent.text(task, plan, records)

            service.update_pull_request(
                int(existing["number"]),
                heading,
                body,
            )

        except (GitHubError, OSError, ValueError) as error:

            print(f"PULL REQUEST AGENT: sync failed: {error}")

            return PullRequestInfo(
                branch=branch,
                state=PullRequestState.FAILED,
                error=str(error),
            )

        return PullRequestAgent.to_info(
            existing,
            branch,
            str((existing.get("base") or {}).get("ref") or ""),
        )

    @staticmethod
    def refresh(task: Task) -> PullRequestInfo:
        """Reads the current state of an existing request."""

        info = task.pull_request

        if not info.id:
            return info

        try:
            service = PullRequestAgent.service(task)

            data = service.read_pull_request(info.id)

        except (GitHubError, OSError, ValueError) as error:

            print(f"PULL REQUEST AGENT: read failed: {error}")

            return info

        return PullRequestAgent.to_info(
            data,
            info.branch,
            info.base,
        )
